"""Refresh the static price files. Run once a day, just after the 00:00 UTC daily close.

data/btc-data.js   Month-end closes and halving cycles. Historical months are frozen; only the
                   newest stored month (which may still be in progress) and any later months are
                   rewritten. The in-progress 2024 halving cycle is rescaled to its range so far.
data/btc-daily.js  Every completed UTC daily close since the first halving (Nov 28, 2012), plus a
                   rolling 35-day window of completed 6-hour closes. Past days are frozen and only
                   appended. Days before July 20, 2015 (where Coinbase's history begins) come from
                   Bitstamp and are written once by --backfill.
                   Both series are stored as a start time and a contiguous array of closes (gaps in
                   the exchange data are filled with the previous close) to keep the file small.

Prices are Coinbase BTC-USD candle closes, except the pre-2015 daily closes noted above.
Usage: python3 scripts/update_data.py              daily refresh (standard library only)
       python3 scripts/update_data.py --backfill   one-time: prepend 2012-2015 daily closes
"""
import json
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_JS = os.path.join(ROOT, "data", "btc-data.js")
DAILY_JS = os.path.join(ROOT, "data", "btc-daily.js")
API = "https://api.exchange.coinbase.com/products/BTC-USD/candles"
CANDLES = API + "?granularity=86400"
CURRENT_CYCLE = ("c2024", "2024-04", "2028-04")  # id, first month, first month of the next cycle
DAILY_FIRST = "2015-07-20"   # first full day of Coinbase BTC-USD daily candles
BACKFILL_FIRST = "2012-11-28"  # first halving; earlier days come from Bitstamp
BITSTAMP = "https://www.bitstamp.net/api/v2/ohlc/btcusd/?step=86400&limit=1000&start=%d"
DAY, H6 = 86400, 21600
H6_WINDOW_DAYS = 35


def load():
    src = open(DATA_JS).read()
    return json.loads(re.search(r"window\.BTC_DATA = (\{.*\});", src, re.S).group(1))


def save(data):
    with open(DATA_JS, "w") as f:
        f.write("/* Generated by scripts/update_data.py. Do not edit by hand. */\n")
        f.write("window.BTC_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")


def fetch_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": "btc-graph-updater"})
    try:
        return json.load(urllib.request.urlopen(req, timeout=30))
    except urllib.error.URLError:
        # python.org builds on macOS often lack a CA bundle; fall back to the system curl
        return json.loads(subprocess.check_output(["curl", "-sf", "-m", "30", url]))


def daily_closes():
    rows = fetch_json(CANDLES)
    # rows: [time, low, high, open, close, volume], newest first
    return sorted((datetime.fromtimestamp(r[0], timezone.utc), float(r[4])) for r in rows)


def candles(gran, start, end):
    """Completed closes {bucket start (unix s): close} for [start, end), paged 299 at a time."""
    out, now = {}, time.time()
    for s in range(start, end, 299 * gran):
        e = min(end, s + 299 * gran)
        url = "%s?granularity=%d&start=%s&end=%s" % (API, gran, iso(s), iso(e))
        for r in fetch_json(url):
            if start <= r[0] < end and r[0] + gran <= now:
                out[r[0]] = round(float(r[4]), 2)
        time.sleep(0.2)  # stay well under the public rate limit
    return out


def iso(ts):
    return datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def day_ts(ymd):
    return int(datetime.strptime(ymd, "%Y-%m-%d").replace(tzinfo=timezone.utc).timestamp())


def contiguous(found, start, gran, until, prev=None):
    """Closes for every bucket from start up to the last completed one, forward-filling gaps."""
    closes = []
    for ts in range(start, until, gran):
        if ts + gran > time.time():
            break
        prev = found.get(ts, prev)
        if prev is None:
            raise SystemExit("no close for the first bucket %s" % iso(ts))
        closes.append(prev)
    return closes


def update_daily_file():
    if os.path.exists(DAILY_JS):
        src = open(DAILY_JS).read()
        daily = json.loads(re.search(r"window\.BTC_DAILY = (\{.*\});", src, re.S).group(1))
    else:
        daily = {"daily": {"start": DAILY_FIRST, "closes": []}}
    d = daily["daily"]
    first = day_ts(d["start"])
    next_day = first + len(d["closes"]) * DAY  # past days are frozen: only fetch what's missing
    now = int(time.time())
    if next_day + DAY <= now:
        prev = d["closes"][-1] if d["closes"] else None
        d["closes"] += contiguous(candles(DAY, next_day, now), next_day, DAY, now, prev)

    h6_start = (now - H6_WINDOW_DAYS * DAY) // H6 * H6
    daily["h6"] = {"start": h6_start, "closes": contiguous(candles(H6, h6_start, now), h6_start, H6, now)}
    daily["updated"] = iso(now)

    with open(DAILY_JS, "w") as f:
        f.write("/* Generated by scripts/update_data.py. Do not edit by hand.\n"
                "   daily: UTC day closes from daily.start, one per day.\n"
                "   h6: 6-hour closes from h6.start (unix seconds), one per 6 hours. */\n")
        f.write("window.BTC_DAILY = " + json.dumps(daily, separators=(",", ":")) + ";\n")
    last = datetime.fromtimestamp(first + (len(d["closes"]) - 1) * DAY, timezone.utc)
    print("daily file: %d days through %s, %d six-hour closes" % (len(d["closes"]), last.date(), len(daily["h6"]["closes"])))


def backfill():
    """Prepend Bitstamp daily closes from BACKFILL_FIRST up to the first stored day (run once)."""
    src = open(DAILY_JS).read()
    head = src[:src.index("window.BTC_DAILY")]
    daily = json.loads(re.search(r"window\.BTC_DAILY = (\{.*\});", src, re.S).group(1))
    d = daily["daily"]
    first, start = day_ts(d["start"]), day_ts(BACKFILL_FIRST)
    if first <= start:
        print("daily file already starts at", d["start"])
        return
    found, s = {}, start
    while s < first:
        rows = fetch_json(BITSTAMP % s)["data"]["ohlc"]
        if not rows:
            break
        for r in rows:
            found[int(r["timestamp"])] = round(float(r["close"]), 2)
        s = int(rows[-1]["timestamp"]) + DAY
        time.sleep(0.5)
    closes, prev = [], None
    for ts in range(start, first, DAY):
        prev = found.get(ts, prev)
        if prev is None:
            raise SystemExit("no Bitstamp close for %s" % iso(ts))
        closes.append(prev)
    d["start"], d["closes"] = BACKFILL_FIRST, closes + d["closes"]
    with open(DAILY_JS, "w") as f:
        f.write(head + "window.BTC_DAILY = " + json.dumps(daily, separators=(",", ":")) + ";\n")
    print("backfilled %d days from Bitstamp (%s to %s)" % (len(closes), BACKFILL_FIRST, iso(first - DAY)[:10]))


def months_between(a, b):
    return (int(b[:4]) - int(a[:4])) * 12 + int(b[5:]) - int(a[5:])


def main():
    data = load()
    closes = daily_closes()
    month_close = {}
    for day, close in closes:
        month_close[day.strftime("%Y-%m")] = (day, close)  # sorted ascending, so last day wins

    monthly = data["monthly"]
    first_open = monthly[-1]["date"]  # newest stored month may still be in progress
    monthly[:] = [p for p in monthly if p["date"] < first_open]
    for ym in sorted(k for k in month_close if k >= first_open):
        monthly.append({"date": ym, "usd": round(month_close[ym][1], 2)})

    cid, start, end = CURRENT_CYCLE
    cyc = data["cycles"][cid]
    pts = [{"m": months_between(start, p["date"]), "date": p["date"], "usd": p["usd"]}
           for p in monthly if start <= p["date"] < end]
    lo = min(pts, key=lambda p: p["usd"])
    hi = max(pts, key=lambda p: p["usd"])
    for p in pts:
        p["pct"] = round((p["usd"] - lo["usd"]) / (hi["usd"] - lo["usd"]) * 100, 1)
    cyc.update(lo=lo["usd"], hi=hi["usd"], loDate=lo["date"], hiDate=hi["date"], points=pts)

    last_day, last_close = closes[-1]
    data["latest"] = {"date": last_day.strftime("%Y-%m-%d"), "usd": round(last_close, 2)}
    data["updated"] = last_day.strftime("%Y-%m-%d")
    save(data)
    print("updated", data["updated"], "close", last_close, "months", len(monthly))
    update_daily_file()


if __name__ == "__main__":
    if "--backfill" in sys.argv:
        backfill()
    else:
        main()
